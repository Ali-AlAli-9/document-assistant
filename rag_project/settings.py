# Password hashing
# https://docs.djangoproject.com/en/6.0/ref/settings/#auth-password-hashers
#
# Argon2id, NOT Django 6.0's PBKDF2 default at 1,200,000 iterations: measured,
# that costs 8.29s per login on the development machine while the 17 SQL queries
# around it total 13ms. Django's own Argon2 defaults are not used either — its
# parallelism=8 oversubscribes a 1-2 vCPU service. Full reasoning and the
# measured table live in core/password_hashers.py.
#
# The old hashers stay listed below on purpose, not for compatibility with a
# live database only: check_password() verifies against the algorithm stored IN
# each hash, so the PBKDF2 entry is what lets existing accounts log in once and
# be re-hashed to Argon2id. Removing it would lock out every existing user.
PASSWORD_HASHERS = [
    'core.password_hashers.Argon2idHasher',
    'django.contrib.auth.hashers.PBKDF2PasswordHasher',
    'django.contrib.auth.hashers.PBKDF2SHA1PasswordHasher',
]

