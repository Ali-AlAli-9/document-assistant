    # Render (and every other managed host) terminates TLS and forwards plain
    # HTTP to the container, tagging it with X-Forwarded-Proto: https. Without
    # this Django believes every request arrived over http and
    # SECURE_SSL_REDIRECT sends it back to https forever — an infinite redirect
    # loop that shows up as a blank page on the deployed site.
    SECURE_PROXY_SSL_HEADER = ('HTTP_X_FORWARDED_PROTO', 'https')

    # The platform's liveness probe reaches the container directly over plain
    # HTTP, so SECURE_SSL_REDIRECT would answer it with a 301 to the public
    # https URL and the platform would report the service as unhealthy. The
    # health endpoint returns nothing but status flags, and external traffic
    # still hits TLS at the platform's edge.
    SECURE_REDIRECT_EXEMPT = [r'^api/health/']